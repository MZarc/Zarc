//! The Zarc key hierarchy.
//!
//! ```text
//!  Android Keystore (non-exportable AES-256-GCM key, hardware backed when
//!  the platform provides it)
//!        │  wraps / unwraps
//!        ▼
//!  Vault Master Key (VMK, 256-bit, random)
//!        │  wraps / unwraps (XChaCha20-Poly1305-IETF, random 192-bit nonce)
//!        ▼
//!  Data Encryption Key (DEK, 256-bit, fresh per object)
//!        │  encrypts
//!        ▼
//!  Object content (XChaCha20-Poly1305 secretstream)
//! ```
//!
//! The VMK is produced by the platform (Kotlin) adapter and handed to the Rust
//! core for the duration of a single operation. The Rust core never persists
//! it. The DEK exists only for the duration of one object and is stored on
//! disk only in its wrapped form.
//!
//! See `docs/KEY_MANAGEMENT.md` for the full lifecycle and loss semantics.
//!
//! This module contains no `unsafe` code.
//!
//! The only `unsafe` in the workspace is the libsodium FFI layer in
//! [`crate::sodium::ffi`].

#![forbid(unsafe_code)]

use zeroize::{Zeroize, ZeroizeOnDrop};

use crate::error::{Error, Result};
use crate::sodium;

/// Length of the vault master key in bytes.
pub const VMK_LEN: usize = 32;

/// Length of a per-object data encryption key in bytes.
pub const DEK_LEN: usize = 32;

/// Length of the wrapping nonce in bytes.
pub const NONCE_LEN: usize = 24;

/// Length of the wrapping authentication tag in bytes.
pub const MAC_LEN: usize = 16;

/// The vault master key.
///
/// It unwraps per-object data keys. It is held in memory only while an object
/// is encrypted or decrypted and is zeroized when dropped.
#[derive(Clone, Zeroize, ZeroizeOnDrop)]
pub struct VaultMasterKey([u8; VMK_LEN]);

impl VaultMasterKey {
    /// Wrap raw key bytes.
    #[must_use]
    pub fn from_bytes(bytes: [u8; VMK_LEN]) -> Self {
        Self(bytes)
    }

    /// # Errors
    /// #
    /// # Returns [`crate::Error`] when the operation cannot be completed; see
    /// # the error taxonomy in [`crate::error`] for the individual failure modes.
    /// Parse raw key bytes of the expected length.
    pub fn from_slice(bytes: &[u8]) -> Result<Self> {
        let array: [u8; VMK_LEN] = bytes.try_into().map_err(|_| {
            Error::InvalidKey(format!(
                "vault master key must be exactly {VMK_LEN} bytes, got {}",
                bytes.len()
            ))
        })?;
        Ok(Self(array))
    }

    /// # Errors
    /// #
    /// # Returns [`crate::Error`] when the operation cannot be completed; see
    /// # the error taxonomy in [`crate::error`] for the individual failure modes.
    /// Generate a fresh random vault master key.
    pub fn generate() -> Result<Self> {
        let mut bytes = [0u8; VMK_LEN];
        sodium::random_bytes(&mut bytes)?;
        Ok(Self(bytes))
    }

    /// Borrow the raw key bytes.
    #[must_use]
    pub fn as_bytes(&self) -> &[u8; VMK_LEN] {
        &self.0
    }
}

/// A per-object data encryption key.
#[derive(Clone, Zeroize, ZeroizeOnDrop)]
pub struct DataEncryptionKey([u8; DEK_LEN]);

impl DataEncryptionKey {
    /// Wrap raw key bytes.
    #[must_use]
    pub fn from_bytes(bytes: [u8; DEK_LEN]) -> Self {
        Self(bytes)
    }

    /// # Errors
    /// #
    /// # Returns [`crate::Error`] when the operation cannot be completed; see
    /// # the error taxonomy in [`crate::error`] for the individual failure modes.
    /// Generate a fresh random data encryption key.
    pub fn generate() -> Result<Self> {
        let mut bytes = [0u8; DEK_LEN];
        sodium::random_bytes(&mut bytes)?;
        Ok(Self(bytes))
    }

    /// Borrow the raw key bytes.
    #[must_use]
    pub fn as_bytes(&self) -> &[u8; DEK_LEN] {
        &self.0
    }
}

/// A data key in its wrapped (on-disk) form.
#[derive(Clone)]
pub struct WrappedDataKey {
    /// Random nonce used for the wrapping operation.
    pub nonce: [u8; NONCE_LEN],
    /// Ciphertext (the encrypted data key).
    pub ciphertext: Vec<u8>,
    /// Authentication tag over the ciphertext and the associated data.
    pub mac: [u8; MAC_LEN],
}

/// # Errors
/// #
/// # Returns [`crate::Error`] when the operation cannot be completed; see
/// # the error taxonomy in [`crate::error`] for the individual failure modes.
/// Wrap a data encryption key under the vault master key.
///
/// `nonce` must be a fresh, random 192-bit value. It is generated by the
/// caller so that it can be stored in (and authenticated through) the object
/// header before the wrapping happens.
///
/// `aad` is the associated data that binds the envelope to its object; it is
/// authenticated but not encrypted.
pub fn wrap_data_key(
    vmk: &VaultMasterKey,
    dek: &DataEncryptionKey,
    nonce: &[u8; NONCE_LEN],
    aad: &[u8],
) -> Result<WrappedDataKey> {
    let (ciphertext, mac) = sodium::aead_seal(vmk.as_bytes(), nonce, aad, dek.as_bytes())?;
    let mut mac_array = [0u8; MAC_LEN];
    if mac.len() != MAC_LEN {
        return Err(Error::Crypto(format!(
            "unexpected AEAD tag length {}",
            mac.len()
        )));
    }
    mac_array.copy_from_slice(&mac);
    Ok(WrappedDataKey {
        nonce: *nonce,
        ciphertext,
        mac: mac_array,
    })
}

/// # Errors
/// #
/// # Returns [`crate::Error`] when the operation cannot be completed; see
/// # the error taxonomy in [`crate::error`] for the individual failure modes.
/// Unwrap a data encryption key.
///
/// The associated data must match the value used when wrapping. Any mismatch,
/// or any modification of the envelope, is reported as an authentication
/// failure.
pub fn unwrap_data_key(
    vmk: &VaultMasterKey,
    wrapped: &WrappedDataKey,
    aad: &[u8],
) -> Result<DataEncryptionKey> {
    if wrapped.ciphertext.len() != DEK_LEN {
        return Err(Error::Format(format!(
            "wrapped data key must be {DEK_LEN} bytes, got {}",
            wrapped.ciphertext.len()
        )));
    }
    let plaintext = sodium::aead_open(
        vmk.as_bytes(),
        &wrapped.nonce,
        aad,
        &wrapped.ciphertext,
        &wrapped.mac,
    )?;
    if plaintext.len() != DEK_LEN {
        return Err(Error::Crypto(format!(
            "unwrapped data key has unexpected length {}",
            plaintext.len()
        )));
    }
    let mut bytes = [0u8; DEK_LEN];
    bytes.copy_from_slice(&plaintext);
    Ok(DataEncryptionKey::from_bytes(bytes))
}

/// The format of a sealed blob.
///
/// ```text
/// version (1) | nonce (24) | ciphertext | tag (16)
/// ```
pub const SEALED_BLOB_VERSION: u8 = 1;

/// # Errors
/// #
/// # Returns [`crate::Error`] when the operation cannot be completed; see
/// # the error taxonomy in [`crate::error`] for the individual failure modes.
/// Seal an arbitrary blob under the vault master key.
///
/// This is used for the metadata index and for the thumbnails of the gallery:
/// everything that describes the vault stays encrypted, exactly like the media
/// itself.
pub fn seal_blob(vmk: &VaultMasterKey, plaintext: &[u8]) -> Result<Vec<u8>> {
    let mut nonce = [0u8; 24];
    sodium::random_bytes(&mut nonce)?;
    let (ciphertext, mac) = sodium::aead_seal(vmk.as_bytes(), &nonce, b"zarc.blob.v1", plaintext)?;
    let mut out = Vec::with_capacity(1 + 24 + ciphertext.len() + mac.len());
    out.push(SEALED_BLOB_VERSION);
    out.extend_from_slice(&nonce);
    out.extend_from_slice(&ciphertext);
    out.extend_from_slice(&mac);
    Ok(out)
}

/// # Errors
/// #
/// # Returns [`crate::Error`] when the operation cannot be completed; see
/// # the error taxonomy in [`crate::error`] for the individual failure modes.
/// Open a blob that was sealed with [`seal_blob`].
pub fn open_blob(vmk: &VaultMasterKey, blob: &[u8]) -> Result<Vec<u8>> {
    if blob.len() < 1 + 24 + 16 {
        return Err(Error::Format("the sealed blob is truncated".into()));
    }
    if blob[0] != SEALED_BLOB_VERSION {
        return Err(Error::UnsupportedVersion(blob[0]));
    }
    let mut nonce = [0u8; 24];
    nonce.copy_from_slice(&blob[1..25]);
    let ciphertext = &blob[25..blob.len() - 16];
    let mac = &blob[blob.len() - 16..];
    sodium::aead_open(vmk.as_bytes(), &nonce, b"zarc.blob.v1", ciphertext, mac)
}

/// # Errors
/// #
/// # Returns [`crate::Error`] when the operation cannot be completed; see
/// # the error taxonomy in [`crate::error`] for the individual failure modes.
/// Derive a purpose bound subkey from the vault master key.
///
/// The derivation uses HKDF-SHA256 from the same library, with a distinct
/// `info` label per purpose. A subkey is never used for two different
/// purposes, so a key that leaks in one role cannot be replayed in another.
pub fn derive_subkey(vmk: &VaultMasterKey, info: &[u8]) -> Result<[u8; 32]> {
    sodium::derive_subkey_hkdf_sha256(vmk.as_bytes(), info)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wrap_unwrap_round_trips() {
        let vmk = VaultMasterKey::generate().unwrap();
        let dek = DataEncryptionKey::generate().unwrap();
        let aad = b"zarc.dek.v1|test-object";
        let nonce = [7u8; NONCE_LEN];
        let wrapped = wrap_data_key(&vmk, &dek, &nonce, aad).unwrap();
        assert_eq!(wrapped.ciphertext.len(), DEK_LEN);
        assert_ne!(wrapped.ciphertext, dek.as_bytes());
        let unwrapped = unwrap_data_key(&vmk, &wrapped, aad).unwrap();
        assert_eq!(unwrapped.as_bytes(), dek.as_bytes());
    }

    #[test]
    fn wrong_vmk_fails() {
        let vmk = VaultMasterKey::generate().unwrap();
        let other = VaultMasterKey::generate().unwrap();
        let dek = DataEncryptionKey::generate().unwrap();
        let aad = b"aad";
        let nonce = [7u8; NONCE_LEN];
        let wrapped = wrap_data_key(&vmk, &dek, &nonce, aad).unwrap();
        assert!(matches!(
            unwrap_data_key(&other, &wrapped, aad),
            Err(Error::Authentication(_))
        ));
    }

    #[test]
    fn wrong_aad_fails() {
        let vmk = VaultMasterKey::generate().unwrap();
        let dek = DataEncryptionKey::generate().unwrap();
        let nonce = [7u8; NONCE_LEN];
        let wrapped = wrap_data_key(&vmk, &dek, &nonce, b"aad-1").unwrap();
        assert!(matches!(
            unwrap_data_key(&vmk, &wrapped, b"aad-2"),
            Err(Error::Authentication(_))
        ));
    }

    #[test]
    fn modified_envelope_fails() {
        let vmk = VaultMasterKey::generate().unwrap();
        let dek = DataEncryptionKey::generate().unwrap();
        let aad = b"aad";
        let nonce = [7u8; NONCE_LEN];
        let mut wrapped = wrap_data_key(&vmk, &dek, &nonce, aad).unwrap();
        wrapped.ciphertext[0] ^= 0x01;
        assert!(matches!(
            unwrap_data_key(&vmk, &wrapped, aad),
            Err(Error::Authentication(_))
        ));
    }

    #[test]
    fn a_different_nonce_fails() {
        let vmk = VaultMasterKey::generate().unwrap();
        let dek = DataEncryptionKey::generate().unwrap();
        let aad = b"aad";
        let nonce = [7u8; NONCE_LEN];
        let wrapped = wrap_data_key(&vmk, &dek, &nonce, aad).unwrap();
        let mut tampered = wrapped.clone();
        tampered.nonce[0] ^= 0x01;
        assert!(matches!(
            unwrap_data_key(&vmk, &tampered, aad),
            Err(Error::Authentication(_))
        ));
    }
}
